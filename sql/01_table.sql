-- Завдання 1: партиціонована таблиця T1
-- Партиціонування RANGE по "гуід операції" (UUID v7), партиції помісячні.
-- UUID v7 починається з мітки часу (48 біт, мілісекунди), тому діапазон гуідів = діапазон часу.
-- Скрипт виконується і на основному інстансі, і на репліці.

-- Найменший UUID для заданого моменту часу: мітка часу + нулі. Використовується як межа партиції.
CREATE OR REPLACE FUNCTION uuid7_floor(p_ts timestamptz) RETURNS uuid
LANGUAGE sql IMMUTABLE PARALLEL SAFE
RETURN (lpad(to_hex(floor(extract(epoch FROM p_ts) * 1000)::bigint), 12, '0')
        || repeat('0', 20))::uuid;

CREATE TABLE IF NOT EXISTS t1 (
    op_guid uuid          NOT NULL DEFAULT uuidv7(),
    op_date timestamptz   GENERATED ALWAYS AS (uuid_extract_timestamp(op_guid)) STORED,
    id      bigint        GENERATED BY DEFAULT AS IDENTITY,
    amount  numeric(14,2) NOT NULL,
    status  smallint      NOT NULL DEFAULT 0,
    message jsonb         NOT NULL,
    CONSTRAINT t1_status_valid  CHECK (status IN (0, 1)),
    CONSTRAINT t1_message_valid CHECK (
        message ?& ARRAY['account', 'client_id', 'op_type']
        AND message->>'op_type' IN ('online', 'offline')
    )
) PARTITION BY RANGE (op_guid);

COMMENT ON TABLE  t1         IS 'Операції (T1). Партиції помісячні, ключ партиціонування - op_guid (UUID v7)';
COMMENT ON COLUMN t1.op_guid IS 'Гуід операції, UUID v7 (містить час операції з точністю до мілісекунди)';
COMMENT ON COLUMN t1.op_date IS 'Дата операції: обчислюється з часу в op_guid, тому завжди збігається з ним';
COMMENT ON COLUMN t1.id      IS 'Айді запису';
COMMENT ON COLUMN t1.amount  IS 'Сума';
COMMENT ON COLUMN t1.status  IS 'Стан: 0 - нова, 1 - підтверджена';
COMMENT ON COLUMN t1.message IS 'Повідомлення: account (номер рахунку), client_id (айді клієнта), op_type (online/offline)';

-- Створює партицію на місяць, до якого належить p_month (межі місяця - в UTC).
CREATE OR REPLACE PROCEDURE t1_create_partition(p_month date)
LANGUAGE plpgsql AS $$
DECLARE
    v_start timestamp := date_trunc('month', p_month::timestamp);
    v_from  uuid := uuid7_floor(v_start AT TIME ZONE 'UTC');
    v_to    uuid := uuid7_floor((v_start + interval '1 month') AT TIME ZONE 'UTC');
    v_name  text := 't1_' || to_char(v_start, 'YYYY_MM');
BEGIN
    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS %I PARTITION OF t1 FOR VALUES FROM (%L) TO (%L)',
        v_name, v_from, v_to);
END;
$$;

-- Партиції: 4 попередні місяці, поточний і наступний.
DO $$
DECLARE
    v_month timestamp;
BEGIN
    FOR v_month IN
        SELECT generate_series(
            date_trunc('month', now() AT TIME ZONE 'UTC') - interval '4 months',
            date_trunc('month', now() AT TIME ZONE 'UTC') + interval '1 month',
            interval '1 month')
    LOOP
        CALL t1_create_partition(v_month::date);
    END LOOP;
END;
$$;

-- Запасна партиція для гуідів поза створеними діапазонами (у нормі порожня).
CREATE TABLE IF NOT EXISTS t1_default PARTITION OF t1 DEFAULT;

-- Запити по даті не відсікають партиції автоматично, тому потрібен індекс.
CREATE INDEX IF NOT EXISTS t1_op_date_idx ON t1 (op_date);
